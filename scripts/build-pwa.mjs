import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {installationIcon} from '../lib/branding.ts';

async function files(directory){
 const entries=await readdir(directory,{withFileTypes:true});
 return (await Promise.all(entries.map(entry=>entry.isDirectory()?files(`${directory}/${entry.name}`):`${directory}/${entry.name}`))).flat();
}
const assets=(await files('.next/static')).filter(path=>!path.endsWith('.map')).sort();
const publicAssets=[...(await files('public/branding')).filter(path=>/\/(?:shalom-2026[^/]*|facebook-primary)\.png$/.test(path)),...(await files('public/fonts')),'public/fonts.css','public/offline.html'];
const hash=createHash('sha256');
for(const file of [...assets,...publicAssets,'public/sw.js'])hash.update(file).update(await readFile(file));
const version=hash.digest('hex').slice(0,16);
const emblemImages=[48,64,96,128,256].map(width=>`/_next/image?url=%2Fbranding%2Fshalom-2026-icon.png&w=${width}&q=75`);
const installIcons=['shalom-2026-icon.png',...['180','192','512','maskable-192','maskable-512'].map(size=>`shalom-2026-${size}.png`)].map(installationIcon);
const precache=[...assets.map(path=>path.replace('.next/','/_next/')),...publicAssets.map(path=>path.replace('public/','/')),...installIcons,...emblemImages,'/','/?view=bible','/?view=saved','/?view=devocional'];
await writeFile('public/pwa-build.js',`// Generated by npm run build.\nself.SHALOM_BUILD=${JSON.stringify({version,precache})};\n`);
console.log(`PWA ${version}: ${precache.length} public shell resources.`);
